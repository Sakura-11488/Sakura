#!/usr/bin/env node
/**
 * One-time bootstrap: registers the existing hardcoded PsyopAnime and
 * 2heAnime episode lists with the media-ingest service so their
 * manifest.json files exist and the app can switch to runtime manifests.
 *
 * Run from the repo root (after deploying the ingest service):
 *     MEDIA_INGEST_TOKEN=... node scripts/droplet/media-ingest/bootstrap-manifests.mjs
 *
 * Optionally set MEDIA_INGEST_BASE (default http://165-232-83-159.nip.io/media/v1).
 * Videos already on the droplet are found by path; missing per-episode thumbs
 * (all of 2heAnime's) are generated server-side by ffmpeg during registration.
 */

import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const TOKEN = (process.env.MEDIA_INGEST_TOKEN || '').trim();
if (!TOKEN) {
  console.error('MEDIA_INGEST_TOKEN is required');
  process.exit(1);
}
const BASE = (process.env.MEDIA_INGEST_BASE || 'http://165-232-83-159.nip.io/media/v1').replace(/\/+$/, '');

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ORIGINALS_TS = path.resolve(__dirname, '../../../sakura-mobile/lib/sakura-originals.ts');

async function post(pathname, body) {
  const res = await fetch(`${BASE}${pathname}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${TOKEN}` },
    body: JSON.stringify(body),
  });
  const json = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(`${pathname} → ${res.status}: ${json.error || 'unknown'}`);
  return json;
}

// Parse the hardcoded arrays out of sakura-originals.ts (single source; the
// tuples are simple enough for a tolerant regex).
const src = await readFile(ORIGINALS_TS, 'utf8');

function parseTuples(anchor) {
  const start = src.indexOf(anchor);
  if (start < 0) throw new Error(`Could not find ${anchor} in sakura-originals.ts`);
  const slice = src.slice(start, src.indexOf('];', start));
  const tuples = [];
  const re = /\[\s*(?:(\d+)|'([^']*(?:\\'[^']*)*)')\s*,\s*'([^']*(?:\\'[^']*)*)'\s*,\s*(?:'([^']*(?:\\'[^']*)*)'|"([^"]*)")\s*\]/g;
  let m;
  while ((m = re.exec(slice))) {
    tuples.push({
      first: m[1] ? Number(m[1]) : (m[2] || '').replace(/\\'/g, "'"),
      second: (m[3] || '').replace(/\\'/g, "'"),
      third: (m[4] ?? m[5] ?? '').replace(/\\'/g, "'"),
    });
  }
  return tuples;
}

// ── PsyopAnime: [number, ytId, title] → videos/<ytId>.mp4, thumbs/<ytId>.jpg ──
const psyop = parseTuples('const PSYOP_EP_RAW');
console.log(`Registering ${psyop.length} PsyopAnime episodes…`);
await post('/works', {
  slug: 'psyopanime',
  title: 'PsyopAnime: The Series',
  status: 'Ongoing',
  genres: ['Sci-Fi Action', 'Psychological Thriller', 'Satire'],
  score: 9.9,
});
for (const { first: number, second: ytId, third: title } of psyop) {
  await post('/works/psyopanime/episodes/register', {
    id: `psyop-${ytId}`,
    number,
    title,
    videoUrl: `/psyopanime/videos/${ytId}.mp4`,
    thumbnail: `/psyopanime/thumbs/${ytId}.jpg`,
  });
}

// ── 2heAnime: [slug, file, title] → videos/<file>; thumbs generated by ffmpeg ──
const twoHe = parseTuples('const TWO_HE_EP_RAW');
console.log(`Registering ${twoHe.length} 2heAnime episodes (thumbs auto-generated)…`);
await post('/works', {
  slug: '2heanime',
  title: '2heAnime',
  status: 'Ongoing',
  genres: ['AI Anime', 'Sakura Original', 'Anthology'],
  score: 9.8,
});
let n = 0;
for (const { first: slug, second: file, third: title } of twoHe) {
  n += 1;
  await post('/works/2heanime/episodes/register', {
    id: `2he-${slug}`,
    number: n,
    title,
    videoUrl: `/2heanime/videos/${file}`,
    // thumbnail omitted → ingest service frame-grabs the local video
  });
}

console.log('Done. Verify:');
console.log(`  curl ${BASE}/works/psyopanime/manifest | head`);
console.log(`  curl ${BASE}/works/2heanime/manifest | head`);
