import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'node:test';
import sharp from 'sharp';
import { prepareCardImages } from './prepare-card-images.mjs';
import cardImages from './card-images.cjs';

const { CARD_IMAGE_NAMES, generatedCardImagePath, resolveWebCardImages } = cardImages;
const repositoryMobileRoot = fileURLToPath(new URL('../../sakura-mobile', import.meta.url));

test('web artwork generation reduces actual cover bytes without modifying native originals', async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'sakura-card-images-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const webRoot = path.join(root, 'web');
  const mobileRoot = path.join(root, 'sakura-mobile');
  const sourceDirectory = path.join(mobileRoot, 'assets/images');
  await fs.mkdir(sourceDirectory, { recursive: true });
  const originals = new Map();
  for (const name of CARD_IMAGE_NAMES) {
    const original = await fs.readFile(path.join(repositoryMobileRoot, 'assets/images', name));
    originals.set(name, original);
    await fs.writeFile(path.join(sourceDirectory, name), original);
  }
  const results = await prepareCardImages({ webRoot, mobileRoot });

  await t.test('five covers preserve aspect ratio with a 960px ceiling and real WebP bytes', async () => {
    assert.equal(results.length, 5);
    for (const result of results) {
      const before = await sharp(originals.get(result.name)).metadata();
      const generated = await sharp(generatedCardImagePath(webRoot, result.name)).metadata();
      assert.equal(generated.format, 'webp');
      assert.ok(generated.width <= 960 && generated.height <= 960);
      assert.ok(generated.width <= before.width && generated.height <= before.height);
      assert.ok(Math.abs(generated.width / generated.height - before.width / before.height) < 0.002);
      assert.ok(result.bytes < result.originalBytes);
      assert.deepEqual(await fs.readFile(path.join(sourceDirectory, result.name)), originals.get(result.name));
    }
    const beforeBytes = results.reduce((sum, result) => sum + result.originalBytes, 0);
    const afterBytes = results.reduce((sum, result) => sum + result.bytes, 0);
    assert.ok(afterBytes < beforeBytes * 0.15, `${afterBytes} should be below 15% of ${beforeBytes}`);
    const poster = results.find((result) => result.name === 'burnie-senders-poster.png');
    assert.equal(poster.width, 640);
    assert.equal(poster.height, 960);
  });

  await t.test('only web resolutions of allowlisted project artwork use derivatives', () => {
    const original = { type: 'assetFiles', filePaths: [path.join(sourceDirectory, CARD_IMAGE_NAMES[0])] };
    const resolved = resolveWebCardImages(original, 'web', { webRoot, mobileRoot });
    assert.deepEqual(resolved.filePaths, [generatedCardImagePath(webRoot, CARD_IMAGE_NAMES[0])]);
    assert.equal(resolveWebCardImages(original, 'ios', { webRoot, mobileRoot }), original);
    assert.equal(resolveWebCardImages(original, 'android', { webRoot, mobileRoot }), original);
    for (const source of [path.join(sourceDirectory, 'icon.png'), path.join(sourceDirectory, 'logo.png'),
      path.join(root, 'foreign/assets/images', CARD_IMAGE_NAMES[0])]) {
      const asset = { type: 'assetFiles', filePaths: [source] };
      assert.deepEqual(resolveWebCardImages(asset, 'web', { webRoot, mobileRoot }), asset);
    }
    const module = { type: 'sourceFile', filePath: path.join(mobileRoot, 'lib/sakura-originals.ts') };
    assert.equal(resolveWebCardImages(module, 'web', { webRoot, mobileRoot }), module);
  });

  await t.test('unchanged generation preserves output mtimes for Metro caches', async () => {
    const output = generatedCardImagePath(webRoot, CARD_IMAGE_NAMES[0]);
    const marker = new Date('2000-01-01T00:00:00Z');
    await fs.utimes(output, marker, marker);
    await prepareCardImages({ webRoot, mobileRoot });
    assert.equal((await fs.stat(output)).mtimeMs, marker.getTime());
  });

  await t.test('fresh source artwork replaces the generated bytes on the next build', async () => {
    const name = CARD_IMAGE_NAMES[0];
    const output = generatedCardImagePath(webRoot, name);
    const before = await fs.readFile(output);
    await sharp({ create: { width: 120, height: 180, channels: 4, background: '#123456' } })
      .png().toFile(path.join(sourceDirectory, name));
    await prepareCardImages({ webRoot, mobileRoot });
    assert.notDeepEqual(await fs.readFile(output), before);
    const image = await sharp(output).metadata();
    assert.equal(image.width, 120);
    assert.equal(image.height, 180);
  });

  await t.test('direct Metro use before generation falls back to existing source artwork', async () => {
    const name = CARD_IMAGE_NAMES[0];
    await fs.rm(generatedCardImagePath(webRoot, name));
    const original = { type: 'assetFiles', filePaths: [path.join(sourceDirectory, name)] };
    assert.deepEqual(resolveWebCardImages(original, 'web', { webRoot, mobileRoot }), original);
  });
});
